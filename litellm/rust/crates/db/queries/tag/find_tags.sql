SELECT t.tag_name AS "tag_name!",
       t.description,
       t.models,
       t.model_info AS "model_info: RawJson",
       t.spend AS "spend!",
       t.budget_id,
       t.created_at AS "created_at!",
       t.created_by,
       t.updated_at AS "updated_at!",
       b.budget_id AS "budget_budget_id?",
       b.name AS "budget_name?",
       b.max_budget AS "budget_max_budget?",
       b.soft_budget AS "budget_soft_budget?",
       b.max_parallel_requests AS "budget_max_parallel_requests?",
       b.tpm_limit AS "budget_tpm_limit?",
       b.rpm_limit AS "budget_rpm_limit?",
       b.tpd_limit AS "budget_tpd_limit?",
       b.model_max_budget AS "budget_model_max_budget?: RawJson",
       b.model_tpm_limit AS "budget_model_tpm_limit?: RawJson",
       b.model_rpm_limit AS "budget_model_rpm_limit?: RawJson",
       b.budget_duration AS "budget_budget_duration?",
       b.budget_limits AS "budget_budget_limits?: RawJson",
       b.cap_policy AS "budget_cap_policy?",
       b.budget_reset_at AS "budget_budget_reset_at?",
       b.budget_reset_count AS "budget_budget_reset_count?",
       b.allowed_models AS "budget_allowed_models?",
       b.temp_budget_increase AS "budget_temp_budget_increase?",
       b.temp_budget_expiry AS "budget_temp_budget_expiry?",
       b.created_at AS "budget_created_at?",
       b.created_by AS "budget_created_by?",
       b.updated_at AS "budget_updated_at?",
       b.updated_by AS "budget_updated_by?"
FROM "LiteLLM_TagTable" AS t
LEFT JOIN "LiteLLM_BudgetTable" AS b ON b.budget_id = t.budget_id
WHERE t.tag_name = ANY($1)
