SELECT tm.user_id,
       tm.team_id,
       tm.budget_id,
       tm.spend,
       tm.total_spend,
       b.budget_id AS "b_budget_id?",
       b.name AS "b_name?",
       b.max_budget AS "b_max_budget?",
       b.soft_budget AS "b_soft_budget?",
       b.max_parallel_requests AS "b_max_parallel_requests?",
       b.tpm_limit AS "b_tpm_limit?",
       b.rpm_limit AS "b_rpm_limit?",
       b.tpd_limit AS "b_tpd_limit?",
       b.model_max_budget AS "b_model_max_budget?: RawJson",
       b.model_tpm_limit AS "b_model_tpm_limit?: RawJson",
       b.model_rpm_limit AS "b_model_rpm_limit?: RawJson",
       b.budget_duration AS "b_budget_duration?",
       b.budget_limits AS "b_budget_limits?: RawJson",
       b.cap_policy AS "b_cap_policy?",
       b.budget_reset_at AS "b_budget_reset_at?",
       b.budget_reset_count AS "b_budget_reset_count?",
       COALESCE(b.allowed_models, '{}') AS "b_allowed_models?",
       b.temp_budget_increase AS "b_temp_budget_increase?",
       b.temp_budget_expiry AS "b_temp_budget_expiry?",
       b.created_at AS "b_created_at?",
       b.created_by AS "b_created_by?",
       b.updated_at AS "b_updated_at?",
       b.updated_by AS "b_updated_by?"
FROM "LiteLLM_TeamMembership" AS tm
LEFT JOIN "LiteLLM_BudgetTable" AS b ON b.budget_id = tm.budget_id
WHERE tm.user_id = $1 AND tm.team_id = $2
